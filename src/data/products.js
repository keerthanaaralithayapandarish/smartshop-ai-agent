/**
 * Helper to get the lowest online price for a product
 */
export function getLowestPrice(product) {
  if (!product || !product.onlineStores || product.onlineStores.length === 0) {
    return { price: product?.originalPrice || 0, store: null, savings: 0 };
  }
  const sorted = [...product.onlineStores].sort((a, b) => a.price - b.price);
  const best = sorted[0];
  const maxPrice = Math.max(...product.onlineStores.map((s) => s.price));
  const diffFromHighest = maxPrice - best.price;
  return {
    price: best.price,
    store: best,
    savings: product.originalPrice - best.price,
    diffFromHighest,
  };
}
